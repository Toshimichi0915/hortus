import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { type Ctx, EFFORTS, type Effort } from "@hortus/core";
import { dataDir, type VibeSettings } from "./config.ts";

const BATCH_PROMPT = `Generate {count} unique 2-4 word loading messages for a "{theme}" theme.
Each message should end with "..."
Be creative, varied, and thematic. No duplicates.
Output one message per line, nothing else. No numbering, no bullets.`;
const SYSTEM = "You generate short themed loading messages and reply with the requested text only.";
const TIMEOUT = 3000;

/** "..." for Latin text, "……" for CJK, replacing whatever dots it ended with. */
export function ellipsis(text: string) {
  const cjk =
    /[\p{Script_Extensions=Han}\p{Script_Extensions=Hiragana}\p{Script_Extensions=Katakana}\p{Script_Extensions=Hangul}\p{Script_Extensions=Bopomofo}]/u.test(
      text,
    );
  return text.replace(/[.…]+$/g, "") + (cjk ? "……" : "...");
}

const slug = (theme: string) =>
  theme
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9_-]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^[-_]+|[-_]+$/g, "") || "theme";
export const vibeFile = (theme: string) => join(dataDir(), "vibes", `${slug(theme)}.txt`);

export function loadVibes(theme: string): string[] {
  try {
    return readFileSync(vibeFile(theme), "utf8")
      .split("\n")
      .map((l) => l.trim())
      .filter((l) => /(?:\.\.\.|…+)$/.test(l))
      .map(ellipsis)
      .filter((l) => l !== "..." && l !== "……");
  } catch {
    return [];
  }
}
export const hasVibeFile = (theme: string) => existsSync(vibeFile(theme));

/** Mulberry32: a seeded PRNG, so a session cycles through every vibe before repeating. */
function mulberry32(seed: number) {
  return () => {
    seed += 0x6d2b79f5;
    let t = seed;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** `provider/model[:effort]` → complete options; "auto" → the session's own. */
function modelSpec(spec: string): { provider?: string; model?: string; effort?: Effort } | undefined {
  if (spec.toLowerCase() === "auto") return {};
  const slash = spec.indexOf("/");
  if (slash <= 0 || slash === spec.length - 1) return;
  const provider = spec.slice(0, slash);
  let model = spec.slice(slash + 1);
  const colon = model.lastIndexOf(":");
  const suffix = colon === -1 ? "" : model.slice(colon + 1);
  let effort: Effort | undefined;
  if ((EFFORTS as readonly string[]).includes(suffix)) {
    effort = suffix as Effort;
    model = model.slice(0, colon);
  }
  return { provider, model, effort };
}

async function complete(ctx: Ctx, spec: string, prompt: string, signal: AbortSignal) {
  const opts = modelSpec(spec);
  if (!opts) throw new Error(`Invalid model: ${spec}`);
  const reply = await ctx.complete({ ...opts, system: SYSTEM, messages: [{ role: "user", content: prompt }], signal });
  return reply.text ?? "";
}

/**
 * Working vibes: while a run works, `show` gets a themed message ("Engaging warp drive..."): a placeholder at once,
 * then one generated by a model (generate mode) or the next from a pre-generated file (file mode), refreshed on tool
 * calls at most every `refreshInterval`.
 */
export function vibes(settings: () => VibeSettings, show: (message: string | undefined) => void) {
  let current: AbortController | undefined;
  let busy = false;
  let last = 0;
  let recent: string[] = [];
  let cache: { theme: string; vibes: string[]; seed: number; index: number } | undefined;

  const fromFile = (s: VibeSettings) => {
    const theme = s.theme as string;
    if (cache?.theme !== theme) cache = { theme, vibes: loadVibes(theme), seed: Date.now(), index: 0 };
    if (!cache.vibes.length) return ellipsis(s.fallback);
    const rng = mulberry32(cache.seed);
    const order = cache.vibes.map((_, i) => i);
    for (let i = order.length - 1; i > 0; i--) {
      const j = Math.floor(rng() * (i + 1));
      [order[i], order[j]] = [order[j] as number, order[i] as number];
    }
    return cache.vibes[order[cache.index++ % order.length] as number] as string;
  };

  const parse = (s: VibeSettings, text: string) => {
    let v = ellipsis((text.trim().split("\n")[0] ?? "").trim().replace(/^["']|["']$/g, ""));
    if (v.length > s.maxLength) v = ellipsis(v.slice(0, s.maxLength - 3));
    return !v || v === "..." || v === "……" ? ellipsis(s.fallback) : v;
  };

  const update = async (ctx: Ctx, task: string) => {
    const s = settings();
    if (!s.theme) return;
    if (s.mode === "file") return show(fromFile(s));
    const controller = new AbortController();
    current?.abort();
    current = controller;
    const prompt = s.prompt
      .replace(/\{theme\}/g, s.theme)
      .replace(/\{task\}/g, task.slice(0, 100))
      .replace(/\{exclude\}/g, recent.length ? `Don't use: ${recent.join(", ")}` : "");
    try {
      const vibe = parse(
        s,
        await complete(ctx, s.model, prompt, AbortSignal.any([controller.signal, AbortSignal.timeout(TIMEOUT)])),
      );
      if (!busy || controller.signal.aborted) return;
      if (vibe !== ellipsis(s.fallback)) recent = [vibe, ...recent.filter((r) => r !== vibe)].slice(0, 5);
      show(vibe);
    } catch {
      // the placeholder stays
    }
  };

  return {
    reset() {
      recent = [];
      cache = undefined;
    },
    start(ctx: Ctx, prompt: string) {
      const s = settings();
      busy = true;
      if (!s.theme) return;
      show(ellipsis(`Channeling ${s.theme}`));
      last = Date.now();
      void update(ctx, prompt);
    },
    toolCall(ctx: Ctx, name: string, input: Record<string, unknown>, agentText?: string) {
      const s = settings();
      if (!s.theme || !busy || Date.now() - last < s.refreshInterval) return;
      let hint = `using ${name} tool`;
      if (agentText && agentText.length > 10) hint = agentText.slice(0, 150);
      else if (name === "read" && input.path) hint = `reading file: ${input.path}`;
      else if (name === "write" && input.path) hint = `writing file: ${input.path}`;
      else if (name === "edit" && input.path) hint = `editing file: ${input.path}`;
      else if (name === "bash" && input.command) hint = `running command: ${String(input.command).slice(0, 40)}`;
      last = Date.now();
      void update(ctx, hint);
    },
    end() {
      busy = false;
      current?.abort();
      show(undefined);
    },
  };
}

/** `/vibe generate <theme> [count]`: asks the vibe model for `count` messages and saves them for file mode. */
export async function generateBatch(ctx: Ctx, spec: string, theme: string, count: number) {
  const n = Math.min(Math.max(Math.floor(count), 1), 500);
  const prompt = BATCH_PROMPT.replace(/\{theme\}/g, theme).replace(/\{count\}/g, String(n));
  const text = await complete(ctx, spec, prompt, AbortSignal.timeout(30_000));
  if (!text) throw new Error("Empty response from model");
  const lines = text
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean)
    .map((l) =>
      ellipsis(
        l
          .replace(/^["'\d.\-)\s]+/, "")
          .trim()
          .replace(/["']$/g, ""),
      ),
    )
    .filter((v) => v.length > 3 && v !== "...");
  if (!lines.length) throw new Error("No valid vibes generated");
  mkdirSync(join(dataDir(), "vibes"), { recursive: true });
  writeFileSync(vibeFile(theme), lines.join("\n"));
  return { count: lines.length, path: vibeFile(theme) };
}

export function parseGenerateArgs(args: string[]) {
  if (!args.length) return;
  const last = args.at(-1) ?? "";
  const hasCount = /^\d+$/.test(last) && args.length > 1;
  const theme = (hasCount ? args.slice(0, -1) : args).join(" ");
  return theme ? { theme, count: hasCount ? Math.min(Math.max(Number(last), 1), 500) : 100 } : undefined;
}
